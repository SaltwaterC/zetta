use super::*;

#[test]
fn pq_identity_has_a_canonical_round_trip() {
    let identity = MlKem768X25519Identity::generate();
    let encoded = identity.to_string();
    assert!(encoded.starts_with("AGE-SECRET-KEY-PQ-1"));
    assert_eq!(encoded, encoded.to_ascii_uppercase());
    let parsed = MlKem768X25519Identity::from_str(&encoded).unwrap();
    assert_eq!(parsed.to_string(), encoded);
    let recipient = parsed.to_recipient().to_string();
    assert!(recipient.starts_with("age1pq1"));
    assert_eq!(
        MlKem768X25519Recipient::from_str(&recipient)
            .unwrap()
            .to_string(),
        recipient
    );
}

#[test]
fn pq_age_stanza_round_trips_through_the_age_stream() {
    let identity = MlKem768X25519Identity::generate();
    let recipient = identity.to_recipient().to_string();
    let recipients = RecipientSet::parse(&[recipient]).unwrap();
    let ciphertext = recipients.encrypt(b"post-quantum session state").unwrap();
    let identity = IdentitySet {
        identities: vec![Box::new(identity)],
    };
    assert_eq!(
        *identity.decrypt(&ciphertext).unwrap(),
        b"post-quantum session state"
    );
}

#[test]
fn pq_recipients_cannot_mix_with_classical_recipients() {
    let pq = MlKem768X25519Identity::generate()
        .to_recipient()
        .to_string();
    let classical = age::x25519::Identity::generate().to_public().to_string();
    let error = RecipientSet::parse(&[pq, classical]).unwrap_err();
    assert!(error.to_string().contains("cannot be mixed"));
}

#[test]
fn identity_text_and_the_key_it_decodes_to_are_held_in_erased_memory() {
    let identity = MlKem768X25519Identity::generate();
    let encoded: Zeroizing<String> = identity.encoded();
    assert_eq!(encoded.capacity(), encoded.len());
    let decoded: Zeroizing<Vec<u8>> = bech32_decode(&encoded, PQ_IDENTITY_HRP, true).unwrap();
    assert_eq!(decoded.len(), PQ_PRIVATE_KEY_BYTES);
}

/// A growing `Vec` frees each smaller copy of a key unerased, so the
/// regrouping is sized for its whole result before it starts.
#[test]
fn bech32_regrouping_never_reallocates() {
    for (bytes, from, to, pad) in [
        (vec![0xa5; PQ_PRIVATE_KEY_BYTES], 8, 5, true),
        (
            convert_bits(&[0xa5; PQ_PRIVATE_KEY_BYTES], 8, 5, true)
                .unwrap()
                .to_vec(),
            5,
            8,
            false,
        ),
        (vec![0xa5; PQ_PUBLIC_KEY_BYTES], 8, 5, true),
    ] {
        let regrouped = convert_bits(&bytes, from, to, pad).unwrap();
        assert!(regrouped.capacity() >= regrouped.len());
        assert!(
            regrouped.capacity() - regrouped.len() <= 1,
            "{} bytes held in {}",
            regrouped.len(),
            regrouped.capacity()
        );
    }
}

// Generated by age v1.3.1; see `age-pq-fixtures/README.md` for how.
const AGE_IDENTITY_FILE: &str = include_str!("age-pq-fixtures/identity.txt");
const AGE_RECIPIENT_FILE: &str = include_str!("age-pq-fixtures/recipient.txt");
const AGE_PLAINTEXT: &[u8] = include_bytes!("age-pq-fixtures/plaintext.txt");
const AGE_CIPHERTEXT: &[u8] = include_bytes!("age-pq-fixtures/ciphertext.age");
const AGE_ARMORED_CIPHERTEXT: &[u8] = include_bytes!("age-pq-fixtures/ciphertext.age.armored");

fn fixture_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("src/tests/persistence/age-pq-fixtures")
        .join(name)
}

fn age_identity_line() -> &'static str {
    AGE_IDENTITY_FILE
        .lines()
        .find(|line| !line.starts_with('#'))
        .unwrap()
}

#[test]
fn age_v1_3_1_identities_and_recipients_read_back_exactly_as_age_wrote_them() {
    let identity = MlKem768X25519Identity::from_str(age_identity_line()).unwrap();
    assert_eq!(identity.to_string(), age_identity_line());
    let recipient = identity.to_recipient().to_string();
    assert_eq!(recipient, AGE_RECIPIENT_FILE.trim());
    assert!(AGE_IDENTITY_FILE.contains(&format!("# public key: {recipient}")));
    assert_eq!(
        MlKem768X25519Recipient::from_str(AGE_RECIPIENT_FILE.trim())
            .unwrap()
            .to_string(),
        recipient
    );
}

#[test]
fn a_file_age_v1_3_1_encrypted_opens_with_its_identity_file() {
    // Through the identity file reader, comments and all, as `-i` would be.
    let identities = IdentitySet::from_paths(&[fixture_path("identity.txt")]).unwrap();
    for ciphertext in [AGE_CIPHERTEXT, AGE_ARMORED_CIPHERTEXT] {
        assert_eq!(*identities.decrypt(ciphertext).unwrap(), AGE_PLAINTEXT);
    }
    let stranger = IdentitySet {
        identities: vec![Box::new(MlKem768X25519Identity::generate())],
    };
    assert!(stranger.decrypt(AGE_CIPHERTEXT).is_err());
}

/// Runs the `age` command, or returns `None` when there is none recent enough
/// to know post-quantum keys: the interoperability above is pinned by the
/// fixtures, and this only adds the other direction where it can.
fn age_command(arguments: &[&std::ffi::OsStr]) -> Option<Vec<u8>> {
    let version = std::process::Command::new("age")
        .arg("--version")
        .output()
        .ok()?;
    let version = String::from_utf8_lossy(&version.stdout);
    let (major, minor) = version
        .trim()
        .trim_start_matches('v')
        .split('.')
        .map(|part| part.parse::<u32>().unwrap_or(0))
        .take(2)
        .collect::<Vec<_>>()
        .try_into()
        .map(|[major, minor]: [u32; 2]| (major, minor))
        .ok()?;
    if (major, minor) < (1, 3) {
        return None;
    }
    let output = std::process::Command::new("age")
        .args(arguments)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "age {arguments:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Some(output.stdout)
}

#[test]
fn age_opens_what_this_implementation_encrypts_and_the_reverse() {
    let directory = tempfile::tempdir().unwrap();
    let identity = MlKem768X25519Identity::generate();
    let identity_path = directory.path().join("ours.txt");
    fs::write(&identity_path, format!("{identity}\n")).unwrap();
    let ours = RecipientSet::parse(&[identity.to_recipient().to_string()]).unwrap();
    let theirs = RecipientSet::parse(&[AGE_RECIPIENT_FILE.trim().to_owned()]).unwrap();
    let to_ours = directory.path().join("to-ours.age");
    let to_theirs = directory.path().join("to-theirs.age");
    fs::write(&to_ours, ours.encrypt(b"sealed by zmux").unwrap()).unwrap();
    fs::write(&to_theirs, theirs.encrypt(b"sealed by zmux").unwrap()).unwrap();

    let fixture = fixture_path("identity.txt");
    let Some(opened) = age_command(&[
        "-d".as_ref(),
        "-i".as_ref(),
        fixture.as_os_str(),
        to_theirs.as_os_str(),
    ]) else {
        eprintln!("no age v1.3 or later on this host; only its fixtures were checked");
        return;
    };
    assert_eq!(opened, b"sealed by zmux");
    // Our identity encoding, read by age.
    let opened = age_command(&[
        "-d".as_ref(),
        "-i".as_ref(),
        identity_path.as_os_str(),
        to_ours.as_os_str(),
    ])
    .unwrap();
    assert_eq!(opened, b"sealed by zmux");
    // Our recipient encoding, read by age, and its ciphertext read by us.
    let recipient = identity.to_recipient().to_string();
    let from_age = age_command(&[
        "-r".as_ref(),
        recipient.as_ref(),
        fixture_path("plaintext.txt").as_os_str(),
    ])
    .unwrap();
    let identities = IdentitySet {
        identities: vec![Box::new(identity)],
    };
    assert_eq!(*identities.decrypt(&from_age).unwrap(), AGE_PLAINTEXT);
}

/// `Stanza` is not `Clone`.
fn copy(stanza: &Stanza) -> Stanza {
    Stanza {
        tag: stanza.tag.clone(),
        args: stanza.args.clone(),
        body: stanza.body.clone(),
    }
}

/// A valid stanza for `identity`, and the file key it wraps.
fn stanza_for(identity: &MlKem768X25519Identity) -> (Stanza, [u8; FILE_KEY_BYTES]) {
    let key = [0x5a; FILE_KEY_BYTES];
    let file_key = FileKey::init_with_mut(|file_key| file_key.copy_from_slice(&key));
    let (mut stanzas, _) =
        age::Recipient::wrap_file_key(&identity.to_recipient(), &file_key).unwrap();
    (stanzas.remove(0), key)
}

fn unwrap(identity: &MlKem768X25519Identity, stanza: &Stanza) -> Option<Result<[u8; 16], ()>> {
    age::Identity::unwrap_stanza(identity, stanza).map(|result| {
        result
            .map(|file_key| file_key.expose_secret().to_owned())
            .map_err(|error| assert!(matches!(error, age::DecryptError::InvalidHeader)))
    })
}

#[test]
fn a_well_formed_stanza_unwraps_to_its_file_key() {
    let identity = MlKem768X25519Identity::generate();
    let (stanza, key) = stanza_for(&identity);
    assert_eq!(stanza.tag, PQ_STANZA);
    assert_eq!(unwrap(&identity, &stanza), Some(Ok(key)));
}

#[test]
fn a_malformed_stanza_is_refused_as_an_invalid_header() {
    let identity = MlKem768X25519Identity::generate();
    let (stanza, _) = stanza_for(&identity);
    let encapsulation = STANDARD_NO_PAD.decode(&stanza.args[0]).unwrap();
    let with = |change: &dyn Fn(&mut Stanza)| {
        let mut stanza = copy(&stanza);
        change(&mut stanza);
        stanza
    };
    let malformed = [
        ("no arguments", with(&|stanza| stanza.args.clear())),
        (
            "two arguments",
            with(&|stanza| stanza.args.push(stanza.args[0].clone())),
        ),
        (
            "not base64",
            with(&|stanza| stanza.args[0].replace_range(0..1, "!")),
        ),
        (
            "padded base64",
            with(&|stanza| {
                stanza.args[0] = base64::engine::general_purpose::STANDARD.encode(&encapsulation)
            }),
        ),
        (
            "a truncated encapsulation",
            with(&|stanza| {
                stanza.args[0] = STANDARD_NO_PAD.encode(&encapsulation[..encapsulation.len() - 1])
            }),
        ),
        (
            "an oversized encapsulation",
            with(&|stanza| {
                stanza.args[0] = STANDARD_NO_PAD.encode([encapsulation.as_slice(), &[0]].concat())
            }),
        ),
        (
            "a short body",
            with(&|stanza| {
                stanza.body.pop();
            }),
        ),
        ("a long body", with(&|stanza| stanza.body.push(0))),
        ("an empty body", with(&|stanza| stanza.body.clear())),
    ];
    for (name, stanza) in malformed {
        assert_eq!(unwrap(&identity, &stanza), Some(Err(())), "{name}");
    }
}

#[test]
fn a_stanza_that_is_not_this_identitys_is_left_for_another() {
    let identity = MlKem768X25519Identity::generate();
    let (stanza, _) = stanza_for(&identity);
    let mut other_tag = copy(&stanza);
    other_tag.tag = "X25519".to_owned();
    let mut tampered = copy(&stanza);
    tampered.body[0] ^= 1;
    for (name, identity, stanza) in [
        ("another tag", &identity, &other_tag),
        ("a tampered body", &identity, &tampered),
        (
            "another identity",
            &MlKem768X25519Identity::generate(),
            &stanza,
        ),
    ] {
        assert_eq!(unwrap(identity, stanza), None, "{name}");
    }
}

#[test]
fn post_quantum_and_classical_recipients_cannot_share_a_file() {
    let pq = MlKem768X25519Identity::generate().to_recipient();
    let classical = age::x25519::Identity::generate().to_public();
    // The configuration refuses the mix, and so does age itself if it is
    // reached another way: the stanza's label keeps a classical recipient from
    // weakening a post-quantum file.
    let encrypted = age::Encryptor::with_recipients(
        [
            &pq as &dyn age::Recipient,
            &classical as &dyn age::Recipient,
        ]
        .into_iter(),
    )
    .and_then(|encryptor| {
        encryptor
            .wrap_output(Vec::new())
            .map(|_| ())
            .map_err(Into::into)
    });
    assert!(encrypted.is_err());
}
